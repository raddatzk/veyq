#!/usr/bin/env python3
"""What builds the release is checked before it runs, and the pins that do the checking hold together (ADR 0057 §6).

**What it asserts.** Every site is found in the tracked tree, never listed (§ *a guard derives its anchor set from
the code*, changes/README.md):

  1. **One generator version.** Every tracked `openapitools.json` names `generator-cli.version`, every tracked
     Gradle script that puts `org.openapitools:openapi-generator` on a classpath names a version, and all of them
     are one value — the clients and the server interfaces are generated by the same generator.
  2. **The JAR pin covers it.** `scripts/openapi_generator_jar.sha256` has a 64-hex SHA-256 line for that value,
     and every tracked `package.json` whose `generate:api` calls `openapi-generator-cli` runs
     `scripts/verify_openapi_generator_jar.mjs` before it — the npm wrapper itself checks nothing, so a pin the
     path does not run is a pin in name only.
  3. **The Gradle distribution is pinned.** Every tracked `gradle-wrapper.properties` carries a 64-hex
     `distributionSha256Sum`.
  4. **Gradle verifies dependencies.** Every Gradle build root (the directory of a tracked `gradlew`) has a
     `gradle/verification-metadata.xml` with `<verify-metadata>true</verify-metadata>`; its only trust rules are
     the `-sources`/`-javadoc` ones an IDE sync needs (those never execute); and no tracked `gradle.properties`
     sets `org.gradle.dependency.verification`, which would turn it lenient or off for every run.

**The defect that bought it.** Live when this guard was written (2026-09-27, cr-build-inputs-pinned): the npm
wrapper downloaded the generator JAR with no checksum and ran any file already in its storage dir, the wrapper
properties carried no distribution checksum, the backend had no verification metadata, and the backend
generated with openapi-generator 7.21.0 while both clients used 7.23.0. Nothing noticed any of it, because a
build that fetches an unchecked input is exactly as green as one that fetches a checked one.

**Its limits — what a green run does NOT prove.** It reads files and contacts no repository, so it cannot tell a
right checksum from a wrong one: that the pin, the wrapper sum and every metadata entry are the published bytes
is what `generate:api`, the wrapper and Gradle each check when they run, and all three are trust-on-first-write
(the pin file's header says how its value was obtained). It does not prove the metadata is COMPLETE — an artifact
it lacks fails the build that resolves it, which is the intended failure, not one this guard foresees; so a new
task, plugin or OS-specific artifact still owes a `--write-verification-metadata` run. It does not see a
`--dependency-verification` flag or `-F` passed on a command line, and it does not verify signatures, only
checksums. The Dockerfile `FROM` lines are `validate_image_pins.py`'s, and npm packages are the lockfile's.
"""
from __future__ import annotations  # `str | None` below — the repo's guards run on Python 3.9

import json
import pathlib
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
PIN_FILE = ROOT / "scripts/openapi_generator_jar.sha256"
VERIFIER = "scripts/verify_openapi_generator_jar.mjs"

SKIP_PREFIXES = ("changes/", "docs/", "wiki/")
HEX64 = re.compile(r"^[0-9a-f]{64}$")
GRADLE_COORD = re.compile(r"""["']org\.openapitools:openapi-generator:([^"'$]+)["']""")
NS = "{https://schema.gradle.org/dependency-verification}"
# The two trust rules an IntelliJ sync needs: it fetches sources and javadoc no task resolves, and neither executes.
IDE_TRUST = {r".*-sources[.]jar", r".*-javadoc[.]jar"}

errors: list[str] = []


def fail(message: str) -> None:
    errors.append(message)


def tracked() -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, text=True)
    if out.returncode != 0:
        fail(f"`git ls-files` failed, so no site could be found and this guard checked NOTHING: {out.stderr.strip()}")
        return []
    return [p for p in out.stdout.split("\0") if p and not p.startswith(SKIP_PREFIXES) and "node_modules/" not in p]


def named(files: list[str], name: str) -> list[str]:
    return [p for p in files if pathlib.PurePosixPath(p).name == name]


def generator_versions(files: list[str]) -> dict[str, str]:
    """{site: version} for every place that chooses which openapi-generator runs."""
    found: dict[str, str] = {}
    for rel in named(files, "openapitools.json"):
        try:
            cli = json.loads((ROOT / rel).read_text())["generator-cli"]
            found[rel] = str(cli["version"])
        except (ValueError, KeyError, TypeError) as e:
            fail(f"{rel}: no generator-cli.version ({e!r})")
    for rel in files:
        if not rel.endswith((".gradle.kts", ".gradle")):
            continue
        for m in GRADLE_COORD.finditer((ROOT / rel).read_text()):
            found[f"{rel} (org.openapitools:openapi-generator)"] = m.group(1)
    return found


def pinned_versions() -> dict[str, str]:
    if not PIN_FILE.is_file():
        fail(f"{PIN_FILE.relative_to(ROOT)} is missing — generate:api has nothing to check the JAR against")
        return {}
    pins: dict[str, str] = {}
    for line in PIN_FILE.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            parts = line.split()
            if len(parts) == 2:
                pins[parts[0]] = parts[1]
    return pins


def check_generator(files: list[str]) -> None:
    versions = generator_versions(files)
    if not any(site.endswith("openapitools.json") for site in versions):
        fail("no tracked openapitools.json names a generator version — re-anchor this guard")
    if not any("openapi-generator)" in site for site in versions):
        fail("no tracked Gradle script names org.openapitools:openapi-generator:<version> — re-anchor this guard")
    distinct = sorted(set(versions.values()))
    if len(distinct) > 1:
        listing = "; ".join(f"{site} = {v}" for site, v in sorted(versions.items()))
        fail(f"the surfaces run {len(distinct)} generator versions ({', '.join(distinct)}), not one: {listing}")
    pins = pinned_versions()
    for version in distinct:
        sha = pins.get(version)
        if sha is None:
            fail(f"{PIN_FILE.relative_to(ROOT)} has no pin for generator {version} — generate:api would refuse it")
        elif not HEX64.match(sha):
            fail(f"{PIN_FILE.relative_to(ROOT)}: the pin for {version} is not a 64-hex SHA-256: {sha!r}")
    for rel in named(files, "package.json"):
        try:
            script = json.loads((ROOT / rel).read_text()).get("scripts", {}).get("generate:api", "")
        except ValueError as e:
            fail(f"{rel} does not parse: {e}")
            continue
        if "openapi-generator-cli" not in script:
            continue
        verify_at, generate_at = script.find(VERIFIER), script.find("openapi-generator-cli")
        if verify_at < 0 or verify_at > generate_at:
            fail(f"{rel}: generate:api runs openapi-generator-cli without running {VERIFIER} before it — "
                 f"the wrapper would run an unchecked JAR")


def check_wrapper(files: list[str]) -> None:
    props = named(files, "gradle-wrapper.properties")
    if not props:
        fail("no tracked gradle-wrapper.properties — re-anchor this guard")
    for rel in props:
        sums = re.findall(r"^distributionSha256Sum=(\S*)\s*$", (ROOT / rel).read_text(), re.MULTILINE)
        if len(sums) != 1 or not HEX64.match(sums[0]):
            fail(f"{rel}: carries no single 64-hex distributionSha256Sum ({sums!r}) — the wrapper would run whatever "
                 f"distribution it downloads. Take the value from Gradle's published .sha256 for distributionUrl "
                 f"(`./gradlew wrapper` drops it unless given --gradle-distribution-sha256-sum)")


def check_verification(files: list[str]) -> None:
    roots = sorted({str(pathlib.PurePosixPath(p).parent) for p in named(files, "gradlew")})
    if not roots:
        fail("no tracked gradlew — re-anchor this guard")
    for root in roots:
        rel = f"{root}/gradle/verification-metadata.xml"
        if rel not in files:
            fail(f"{rel} is not tracked — Gradle verifies no dependency of the build at {root}/")
            continue
        try:
            tree = ET.parse(ROOT / rel).getroot()
        except ET.ParseError as e:
            fail(f"{rel} does not parse: {e}")
            continue
        flag = tree.find(f"{NS}configuration/{NS}verify-metadata")
        if flag is None or (flag.text or "").strip() != "true":
            fail(f"{rel}: <verify-metadata> is not `true` — the file is there and checks nothing")
        if not tree.findall(f"{NS}components/{NS}component"):
            fail(f"{rel}: lists no component — regenerate it with --write-verification-metadata sha256")
        for trust in tree.iter(f"{NS}trust"):
            if dict(trust.attrib) not in ({"file": r, "regex": "true"} for r in IDE_TRUST):
                fail(f"{rel}: trust rule {dict(trust.attrib)} exempts more than the -sources/-javadoc jars an IDE "
                     f"sync fetches — an exempted artifact that executes is an unverified one")
    for rel in named(files, "gradle.properties"):
        for line in (ROOT / rel).read_text().splitlines():
            if re.match(r"^\s*org\.gradle\.dependency\.verification\s*[=:]", line):
                fail(f"{rel}: `{line.strip()}` overrides dependency verification for every build that reads it")


def main() -> int:
    files = tracked()
    if files:
        check_generator(files)
        check_wrapper(files)
        check_verification(files)
    if errors:
        for e in errors:
            print(f"::error::build-input pins: {e}")
        return 1
    print("build-input pins: one generator version, pinned and verified on every generate:api; "
          "wrapper distribution checksummed; Gradle dependency verification on")
    return 0


if __name__ == "__main__":
    sys.exit(main())
