#!/usr/bin/env python3
"""Offline self-test of `renovate_follow.py`: each follow on the shape it was written for and on the forgeries it must
refuse — a metadata "write" that changes a committed checksum, a libwebp pin naming another commit or image, a lock
file with a line of another kind; the gate; and the command line on a real git tree. No network: libwebp's tag list
is a fake. `checks.yml`'s `guards` job runs it.

    python3 scripts/renovate_follow_selftest.py
"""
from __future__ import annotations

import hashlib
import pathlib
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import renovate_follow as df  # noqa: E402

failures: list[str] = []
checks = 0


def check(label: str, ok: bool, detail: str = "") -> None:
    global checks
    checks += 1
    if not ok:
        failures.append(f"{label}{': ' + detail if detail else ''}")


def refuses(label: str, fn, *args) -> None:
    try:
        result = fn(*args)
    except df.Refusal:
        check(label, True)
        return
    check(label, False, f"was not refused, returned {str(result)[:200]}")


# --- what a bump needs --------------------------------------------------------------------------------------------------

got = df.needs(["src/backend/gradle/libs.versions.toml"])
check("needs: a version catalog bump needs the backend's metadata and nothing else",
      got == {"gradle_backend": "true", "gradle_root": "false", "webp": "false", "fuzz": "false"}, str(got))
check("needs: the root wrapper needs the root launcher's metadata",
      df.needs(["gradle/wrapper/gradle-wrapper.properties"])["gradle_root"] == "true"
      and df.needs(["gradle/wrapper/gradle-wrapper.properties"])["gradle_backend"] == "false")
check("needs: buildSrc is the backend's build", df.needs(["src/backend/buildSrc/build.gradle.kts"])["gradle_backend"] == "true")
check("needs: libwebp's pin or the Emscripten image needs the encoder rebuilt",
      df.needs(["src/web/webp-encoder/libwebp.pin"])["webp"] == "true"
      and df.needs(["src/web/webp-encoder/Dockerfile"])["webp"] == "true")
check("needs: a Schemathesis bump needs the lock", df.needs(["tests/fuzz/lock.py"])["fuzz"] == "true")
check("needs: an npm or image bump needs nothing",
      set(df.needs(["pnpm-lock.yaml", "src/tools/Dockerfile", "tests/fuzz/Dockerfile"]).values()) == {"false"})


# --- Gradle verification metadata -------------------------------------------------------------------------------------

HEADER = ('<?xml version="1.0" encoding="UTF-8"?>\n<verification-metadata xmlns="https://schema.gradle.org/dependency-'
          'verification">\n   <configuration>\n      <verify-metadata>true</verify-metadata>\n   </configuration>\n'
          '   <components>\n')
FOOTER = "   </components>\n</verification-metadata>\n"


def component(group: str, name: str, version: str, sha: str = "a" * 64) -> str:
    return (f'      <component group="{group}" name="{name}" version="{version}">\n'
            f'         <artifact name="{name}-{version}.jar">\n'
            f'            <sha256 value="{sha}" origin="Generated by Gradle"/>\n'
            f'         </artifact>\n      </component>\n')


def metadata(*components: str, header: str = HEADER) -> str:
    return header + "".join(components) + FOOTER


committed = metadata(component("a", "lib", "1.0"), component("c", "kept", "2.0"), component("x", "dropped", "1.0"))
written = metadata(component("a", "lib", "1.0"), component("a", "lib", "1.1", "b" * 64), component("c", "kept", "2.0"),
                   component("e", "new", "1.0", "c" * 64), component("x", "dropped", "1.0"))
cold = ["a:lib:1.1", "c:kept:2.0", "e:new:1.0"]
accepted = df.accept_gradle(committed, written, cold)
check("gradle: the replaced version leaves, everything else stays",
      accepted == metadata(component("a", "lib", "1.1", "b" * 64), component("c", "kept", "2.0"),
                           component("e", "new", "1.0", "c" * 64), component("x", "dropped", "1.0")), accepted)
check("gradle: a write that added nothing changes nothing", df.accept_gradle(committed, committed, cold) == committed)
check("gradle: a replaced version the cold home still fetches stays",
      "1.0" in df.accept_gradle(committed, written, cold + ["a:lib:1.0"]).split('name="lib" version="')[1][:3])
refuses("gradle FORGERY: a committed artifact's checksum changed",
        df.accept_gradle, committed, written.replace(component("c", "kept", "2.0"), component("c", "kept", "2.0", "f" * 64)),
        cold)
also_trusted = component("c", "kept", "2.0").replace(
    f'<sha256 value="{"a" * 64}" origin="Generated by Gradle"/>',
    f'<sha256 value="{"a" * 64}" origin="Generated by Gradle"><also-trust value="{"f" * 64}"/></sha256>')
check("gradle: the also-trust forgery below is built", also_trusted != component("c", "kept", "2.0"))
refuses("gradle FORGERY: an also-trust slipped under a committed checksum",
        df.accept_gradle, committed, written.replace(component("c", "kept", "2.0"), also_trusted), cold)
refuses("gradle FORGERY: the trust rules changed",
        df.accept_gradle, committed, written.replace("<verify-metadata>true", "<verify-metadata>false"), cold)
refuses("gradle FORGERY: a committed component vanished",
        df.accept_gradle, committed, written.replace(component("c", "kept", "2.0"), ""), cold)
refuses("gradle FORGERY: a DOCTYPE (entity expansion) is never parsed",
        df.accept_gradle, committed, written.replace("<verification-metadata ", "<!DOCTYPE x [<!ENTITY a 'b'>]>\n<verification-metadata ", 1), cold)
refuses("gradle FORGERY: a malformed checksum on a new component",
        df.accept_gradle, committed, written.replace("c" * 64, "not-hex"), cold)
refuses("gradle: a cold-cache listing that is no coordinate list", df.accept_gradle, committed, written, ["a:lib"])



# --- the WebP encoder -------------------------------------------------------------------------------------------------

TAG, COMMIT, OTHER = "v1.7.0", "1" * 40, "2" * 40
IMAGE = "emscripten/emsdk:7.0.1@sha256:" + "3" * 64
WASM, MJS = b"\0asm-new", b"export default 1;\n"


def pin(tag: str = TAG, commit: str = COMMIT, image: str = IMAGE, files: dict | None = None) -> str:
    files = {"wasm/webp_encoder.wasm": WASM, "wasm/webp_encoder.mjs": MJS} if files is None else files
    lines = ["# written by build.py --write", f"tag {tag}", f"commit {commit}", f"image {image}"]
    lines += [f"sha256 {hashlib.sha256(data).hexdigest()} {rel}" for rel, data in files.items()]
    return "\n".join(lines) + "\n"


def webp_case(root: pathlib.Path, written_pin: str, tree_tag: str = TAG, files: dict | None = None,
              dockerfile_image: str = IMAGE) -> tuple[pathlib.Path, pathlib.Path]:
    tree, derived = root / "tree", root / "derived"
    enc = tree / "src/web/webp-encoder"
    (enc / "wasm").mkdir(parents=True)
    (enc / "Dockerfile").write_text(f"# the toolchain\nFROM {dockerfile_image} AS runtime-webp-encoder\n")
    (enc / "libwebp.pin").write_text(pin(tag=tree_tag, commit="0" * 40, image="old"))
    (derived / "webp" / "wasm").mkdir(parents=True)
    (derived / "webp" / "libwebp.pin").write_text(written_pin)
    for rel, data in ({"wasm/webp_encoder.wasm": WASM, "wasm/webp_encoder.mjs": MJS} if files is None else files).items():
        (derived / "webp" / rel).parent.mkdir(parents=True, exist_ok=True)
        (derived / "webp" / rel).write_bytes(data)
    return tree, derived


def upstream(tag: str) -> str:
    return df.libwebp_commit(tag, lambda: f"{'9' * 40}\trefs/tags/{TAG}\n{COMMIT}\trefs/tags/{TAG}^{{}}\n")


check("libwebp: an annotated tag names its peeled commit, not the tag object", upstream(TAG) == COMMIT)
check("libwebp: a lightweight tag names its own line",
      df.libwebp_commit(TAG, lambda: f"{OTHER}\trefs/tags/{TAG}\n") == OTHER)
refuses("libwebp: a tag upstream does not list", df.libwebp_commit, TAG, lambda: "")
refuses("libwebp: a tag that is no stable vX.Y.Z", df.libwebp_commit, "v1.7.0-rc1", lambda: "")

with tempfile.TemporaryDirectory() as tmp:
    tree, derived = webp_case(pathlib.Path(tmp), pin())
    got = df.accept_webp(tree, derived, upstream)
    check("webp: the written pin and the files it hashes are taken",
          sorted(got) == ["src/web/webp-encoder/libwebp.pin", "src/web/webp-encoder/wasm/webp_encoder.mjs",
                          "src/web/webp-encoder/wasm/webp_encoder.wasm"]
          and got["src/web/webp-encoder/wasm/webp_encoder.wasm"] == WASM, str(sorted(got)))
for label, written_pin, kwargs in (
        ("webp FORGERY: a pin naming another commit than upstream's", pin(commit=OTHER), {}),
        ("webp FORGERY: a pin naming another tag than the pull request's", pin(tag="v1.8.0"), {}),
        ("webp FORGERY: a pin naming another image than the Dockerfile's", pin(image="emscripten/emsdk:6@sha256:" + "4" * 64), {}),
        ("webp FORGERY: a file that does not hash to its line", pin(), {"files": {"wasm/webp_encoder.wasm": b"evil",
                                                                                 "wasm/webp_encoder.mjs": MJS}}),
        # the forged file exists beside the artifact, so only the path rule can refuse it
        ("webp FORGERY: a hashed path outside the encoder's directory",
         pin(files={"../x.yml": b"on: push"}), {"files": {"../x.yml": b"on: push"}}),
        ("webp: a pin line build.py never writes", pin() + "extra line\n", {}),
):
    with tempfile.TemporaryDirectory() as tmp:
        tree, derived = webp_case(pathlib.Path(tmp), written_pin, **kwargs)
        refuses(label, df.accept_webp, tree, derived, upstream)
with tempfile.TemporaryDirectory() as tmp:
    tree, derived = webp_case(pathlib.Path(tmp), pin())
    (derived / "webp" / "libwebp.pin").unlink()
    refuses("webp: an artifact without the written pin", df.accept_webp, tree, derived, upstream)


# --- the fuzzer's lock ------------------------------------------------------------------------------------------------

LOCK = 'SCHEMATHESIS = "schemathesis==4.33.0"\n'
GOOD_LOCK = ("# Schemathesis and everything it installs.\n# Written by ./lock.py.\n"
             "anyio==4.15.1 \\\n    --hash=sha256:" + "a" * 64 + "\n"
             "schemathesis==4.33.0 \\\n    --hash=sha256:" + "b" * 64 + " \\\n    --hash=sha256:" + "c" * 64 + "\n")


def lock_case(root: pathlib.Path, written: str, lock: str = LOCK) -> tuple[pathlib.Path, pathlib.Path]:
    tree, derived = root / "tree", root / "derived"
    (tree / "tests/fuzz").mkdir(parents=True)
    (tree / "tests/fuzz/lock.py").write_text(lock)
    (derived / "fuzz").mkdir(parents=True)
    (derived / "fuzz" / "requirements.txt").write_text(written)
    return tree, derived


with tempfile.TemporaryDirectory() as tmp:
    tree, derived = lock_case(pathlib.Path(tmp), GOOD_LOCK)
    check("lock: a requirements file of pins and hashes that pins lock.py's Schemathesis is taken",
          df.accept_lock(tree, derived) == GOOD_LOCK.encode())
for label, written_lock, lock in (
        ("lock FORGERY: an index URL slipped in", GOOD_LOCK + "--extra-index-url https://evil.example/simple\n", LOCK),
        ("lock FORGERY: an unhashed requirement", GOOD_LOCK + "requests==2.32.0\n", LOCK),
        ("lock FORGERY: a comment after the first pin", GOOD_LOCK.replace("anyio", "# x\nanyio", 1).replace(
            "schemathesis==", "# hidden\nschemathesis==", 1), LOCK),
        ("lock: another Schemathesis than lock.py names", GOOD_LOCK, 'SCHEMATHESIS = "schemathesis==4.34.0"\n'),
        ("lock: a lock.py naming no Schemathesis", GOOD_LOCK, "VERSION = 1\n"),
):
    with tempfile.TemporaryDirectory() as tmp:
        tree, derived = lock_case(pathlib.Path(tmp), written_lock, lock)
        refuses(label, df.accept_lock, tree, derived)


# --- the gate ---------------------------------------------------------------------------------------------------------

REPO, SHA = "owner/veyq", "f" * 40


def api(user: str = df.RENOVATE, ref: str = "renovate/gradle-minor-and-patch", sha: str = SHA,
        authors: tuple = (df.RENOVATE,), head_repo: str = REPO, state: str = "open"):
    def call(path: str):
        if path.endswith("/commits"):
            return [{"author": {"login": a}} for a in authors]
        return {"state": state, "user": {"login": user},
                "head": {"ref": ref, "sha": sha, "repo": {"full_name": head_repo}},
                "base": {"ref": "main", "repo": {"full_name": REPO}}}
    return call


check("gate: Renovate's open pull request is followed",
      df.gate(REPO, 7, SHA, api()) == {"follow": "true", "branch": "renovate/gradle-minor-and-patch", "base_ref": "main"})
check("gate: a branch the follow already pushed to (as Renovate's bot) is still followed",
      df.gate(REPO, 7, SHA, api(authors=(df.RENOVATE, df.RENOVATE)))["follow"] == "true")
check("gate: a branch a person pushed to is left alone",
      df.gate(REPO, 7, SHA, api(authors=(df.RENOVATE, "someone")))["follow"] == "false")
check("gate: a branch Dependabot's follow bot pushed to is left alone",
      df.gate(REPO, 7, SHA, api(authors=(df.RENOVATE, "github-actions[bot]")))["follow"] == "false")
check("gate: a branch that moved since the derive run is left alone", df.gate(REPO, 7, SHA, api(sha="e" * 40))["follow"] == "false")
check("gate: a closed pull request is left alone", df.gate(REPO, 7, SHA, api(state="closed"))["follow"] == "false")
refuses("gate FORGERY: a pull request by anyone but Renovate's App", df.gate, REPO, 7, SHA, api(user="someone"))
refuses("gate FORGERY: Dependabot's pull request", df.gate, REPO, 7, SHA, api(user="dependabot[bot]"))
refuses("gate FORGERY: a head in another repository", df.gate, REPO, 7, SHA, api(head_repo="fork/veyq"))
refuses("gate: a head branch that is not Renovate's", df.gate, REPO, 7, SHA, api(ref="main"))


# --- end to end: the command line on a real git tree ------------------------------------------------------------------

def run_git(cwd: pathlib.Path, *args: str) -> str:
    # A throwaway tree's commits are never signed: a host's signing agent (locked, or absent on a runner) is no input.
    return subprocess.run(["git", "-C", str(cwd), "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false",
                           *args],
                          capture_output=True, text=True, check=True).stdout.strip()


cli = [sys.executable, str(pathlib.Path(__file__).resolve().parent / "renovate_follow.py")]
with tempfile.TemporaryDirectory() as scratch:
    work = pathlib.Path(scratch) / "tree"
    (work / "src/backend/gradle").mkdir(parents=True)
    (work / "src/backend/gradle/verification-metadata.xml").write_text(committed)
    (work / "src/backend/gradle/libs.versions.toml").write_text('[versions]\nlib = "1.0"\n')
    (work / "src/tools").mkdir(parents=True)
    (work / "src/tools/Dockerfile").write_text("FROM rclone/rclone:1.75.0@sha256:" + "1" * 64 + "\n")
    run_git(work, "init", "--quiet")
    run_git(work, "add", "-A")
    run_git(work, "commit", "--quiet", "-m", "base")
    base_sha = run_git(work, "rev-parse", "HEAD")
    message = pathlib.Path(scratch) / "message.txt"

    (work / "src/tools/Dockerfile").write_text("FROM rclone/rclone:1.75.2@sha256:" + "2" * 64 + "\n")
    run_git(work, "commit", "--quiet", "-am", "an image bump")
    ran = subprocess.run(cli + ["follow", "--tree", str(work), "--base", base_sha, "--message", str(message)],
                         capture_output=True, text=True)
    check("end to end: an image bump needs no follow — exit 0, nothing written, no message",
          ran.returncode == 0 and run_git(work, "status", "--porcelain") == "" and not message.exists(),
          ran.stdout + ran.stderr)

    (work / "src/backend/gradle/libs.versions.toml").write_text('[versions]\nlib = "1.1"\n')
    run_git(work, "commit", "--quiet", "-am", "a catalog bump")
    derived = pathlib.Path(scratch) / "derived"
    (derived / "gradle" / "backend").mkdir(parents=True)
    (derived / "gradle" / "backend" / "verification-metadata.xml").write_text(written)
    (derived / "gradle" / "backend" / "cold-cache.json").write_text('["a:lib:1.1", "c:kept:2.0", "e:new:1.0"]')
    needs = subprocess.run(cli + ["needs", "--tree", str(work), "--base", base_sha], capture_output=True, text=True)
    check("end to end: `needs` names the backend's metadata", "gradle_backend=true" in needs.stdout, needs.stdout)
    ran = subprocess.run(cli + ["follow", "--tree", str(work), "--base", base_sha, "--derived", str(derived),
                                "--message", str(message)], capture_output=True, text=True)
    check("end to end: the metadata is written and the message names it",
          ran.returncode == 0 and run_git(work, "status", "--porcelain") == "M src/backend/gradle/verification-metadata.xml"
          and message.read_text().startswith(df.FOLLOW_SUBJECT + "\n"), ran.stdout + ran.stderr)
    run_git(work, "commit", "--quiet", "-a", "-F", str(message))
    message.unlink()
    ran = subprocess.run(cli + ["follow", "--tree", str(work), "--base", base_sha, "--message", str(message)],
                         capture_output=True, text=True)
    check("end to end: on the follow's own commit nothing is followed again, even with no artifact",
          ran.returncode == 0 and run_git(work, "status", "--porcelain") == "" and not message.exists(),
          ran.stdout + ran.stderr)
    (work / "src/backend/gradle/libs.versions.toml").write_text('[versions]\nlib = "1.2"\n')
    run_git(work, "commit", "--quiet", "-am", "another catalog bump")
    ran = subprocess.run(cli + ["follow", "--tree", str(work), "--base", base_sha, "--message", str(message)],
                         capture_output=True, text=True)
    check("end to end: a bump that needs a follow, with no artifact, exits 1 and writes nothing",
          ran.returncode == 1 and run_git(work, "status", "--porcelain") == "", ran.stdout + ran.stderr)

if failures:
    print(f"RENOVATE FOLLOW SELF-TEST FAILED ({len(failures)} of {checks}):")
    for f in failures:
        print("  -", f)
    sys.exit(1)
print(f"renovate follow self-test OK: {checks} checks")
