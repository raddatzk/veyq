#!/usr/bin/env python3
"""The verdicts of scripts/verification_metadata_diff.py, offline: each refusal it promises is one case, each allowance
another, and the command itself runs once against a throwaway git repository (the base, a move, a deletion).

Run by `checks.yml`'s `guards` job. Exit 1 names the first case that went the wrong way.
"""
from __future__ import annotations  # the repo's scripts run on Python 3.9

import pathlib
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import verification_metadata_diff as vm  # noqa: E402

failures: list[str] = []


def check(ok: bool, what: str) -> None:
    if not ok:
        failures.append(what)


A = "a" * 64
B = "b" * 64
C = "c" * 64

CONFIGURATION = """   <configuration>
      <verify-metadata>true</verify-metadata>
      <verify-signatures>false</verify-signatures>
   </configuration>
"""


def metadata(components: str, configuration: str = CONFIGURATION, head: str = "") -> str:
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n{head}'
            f'<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">\n'
            f"{configuration}   <components>\n{components}   </components>\n</verification-metadata>\n")


def component(group: str, name: str, version: str, *artifacts: tuple[str, str]) -> str:
    body = "".join(f'         <artifact name="{a}">\n            <sha256 value="{v}" origin="Generated by Gradle"/>\n'
                   f"         </artifact>\n" for a, v in artifacts)
    return f'      <component group="{group}" name="{name}" version="{version}">\n{body}      </component>\n'


OLD = component("org.x", "lib", "1.0", ("lib-1.0.jar", A), ("lib-1.0.pom", B))
BASE = metadata(OLD)
F = "src/backend/gradle/verification-metadata.xml"


def refused(head: str | None, base: str | None = BASE) -> list[str]:
    return vm.verdicts(F, base, head)


# ---- allowed ------------------------------------------------------------------------------------------------------------
check(refused(BASE) == [], "an unchanged file is refused")
check(refused(metadata(OLD + component("org.x", "lib", "1.1", ("lib-1.1.jar", C)))) == [], "an added version is refused")
check(refused(metadata(component("org.x", "lib", "1.1", ("lib-1.1.jar", C)))) == [],
      "a bump that prunes the version it replaced is refused")
check(refused(metadata(component("org.x", "lib", "1.0", ("lib-1.0.jar", A)))) == [],
      "a kept version that drops one artifact (a POM a module file made unread) is refused")
check(refused(metadata(component("org.x", "lib", "1.0", ("lib-1.0.jar", A), ("lib-1.0.pom", B),
                                 ("lib-1.0-linux.jar", C)))) == [], "a kept version that gains an artifact is refused")
check(refused(BASE, None) == [], "a file with no base is refused on its form")

# ---- refused: the trust already committed changes ------------------------------------------------------------------------
swapped = metadata(component("org.x", "lib", "1.0", ("lib-1.0.jar", C), ("lib-1.0.pom", B)))
got = refused(swapped)
check(len(got) == 1 and "lib-1.0.jar" in got[0] and "other checksums" in got[0],
      f"a changed checksum of a kept artifact passes: {got}")
also = BASE.replace(f'<sha256 value="{A}" origin="Generated by Gradle"/>',
                    f'<sha256 value="{A}" origin="Generated by Gradle">\n               <also-trust value="{C}"/>\n'
                    f"            </sha256>")
check(also != BASE and any("other checksums" in e for e in refused(also)), "an also-trust added to a kept artifact passes")
kind = BASE.replace(f'<sha256 value="{A}"', f'<sha512 value="{A}{A}"')
check(any("other checksums" in e for e in refused(kind)), "a kept artifact's checksum of another kind passes")
opened = metadata(OLD, CONFIGURATION.replace("<verify-metadata>true", "<verify-metadata>false"))
check(any("<configuration> changed" in e for e in refused(opened)), "verification switched off in <configuration> passes")
trusted = metadata(OLD, CONFIGURATION.replace("   </configuration>",
                                              "      <trusted-artifacts>\n         <trust group=\"org.x\"/>\n"
                                              "      </trusted-artifacts>\n   </configuration>"))
check(any("<configuration> changed" in e for e in refused(trusted)), "a trusted artifact added to <configuration> passes")
check(any("is deleted" in e for e in refused(None)), "a deleted file passes")

# ---- refused: the file's form --------------------------------------------------------------------------------------------
check(any("DOCTYPE" in e for e in refused(metadata(OLD, head="<!DOCTYPE x>\n"))), "a DOCTYPE passes")
check(any("twice" in e for e in refused(metadata(OLD + OLD))), "a component listed twice passes")
check(any("well-formed checksum" in e for e in refused(metadata(component("org.y", "z", "1", ("z-1.jar", "XYZ"))), None)),
      "a malformed checksum passes")
check(any("no Gradle verification metadata" in e for e in refused("<other/>")), "another XML document passes")
check(any("does not parse" in e for e in refused("<verification-metadata")), "a broken file passes")

# ---- the command, against a throwaway repository -------------------------------------------------------------------------


def run(repo: pathlib.Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(args, cwd=repo, capture_output=True, text=True)


with tempfile.TemporaryDirectory(prefix="verification_metadata_") as tmp:
    repo = pathlib.Path(tmp)
    (repo / "scripts").mkdir()
    shutil.copy(HERE / "verification_metadata_diff.py", repo / "scripts" / "verification_metadata_diff.py")
    for args in (("git", "init", "-q"), ("git", "config", "user.email", "t@t"), ("git", "config", "user.name", "t"),
                 ("git", "config", "commit.gpgsign", "false")):
        run(repo, *args)
    old = repo / "backend" / "gradle" / "verification-metadata.xml"
    old.parent.mkdir(parents=True)
    old.write_text(BASE)
    run(repo, "git", "add", "-A")
    run(repo, "git", "commit", "-q", "-m", "base")
    base = run(repo, "git", "rev-parse", "HEAD").stdout.strip()
    command = ("python3", "scripts/verification_metadata_diff.py", "--base", base)

    new = repo / "src" / "backend" / "gradle" / "verification-metadata.xml"
    new.parent.mkdir(parents=True)
    run(repo, "git", "mv", "backend/gradle/verification-metadata.xml", "src/backend/gradle/verification-metadata.xml")
    proc = run(repo, *command)
    check(proc.returncode == 0, f"a moved file is refused: {proc.stdout}{proc.stderr}")

    new.write_text(swapped)
    proc = run(repo, *command)
    check(proc.returncode == 1 and "other checksums" in proc.stdout, f"a swap inside a move passes: {proc.stdout}")

    run(repo, "git", "rm", "-q", "-f", "src/backend/gradle/verification-metadata.xml")
    proc = run(repo, *command)
    check(proc.returncode == 1 and "is deleted" in proc.stdout, f"a deleted file passes the command: {proc.stdout}")

    proc = run(repo, "python3", "scripts/verification_metadata_diff.py", "--base", "f" * 40)
    check(proc.returncode == 1 and "no commit" in proc.stdout, f"a base not in the checkout passes: {proc.stdout}")

if failures:
    print("VERIFICATION METADATA SELF-TEST FAILED:")
    for f in failures:
        print(f"  - {f}")
    sys.exit(1)
print("verification metadata self-test OK: every allowance passes, every refusal is red, the command reads its base")
