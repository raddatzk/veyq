package com.veyq.core.tenant

import org.jboss.logging.Logger
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import java.nio.file.attribute.PosixFilePermissions

/**
 * The docker-compose sink (ADR 0063): a Traefik **file-provider** dynamic configuration, written to a volume
 * `traefik` watches with `--providers.file.watch=true`, so a new tenant domain routes on the next hot reload
 * with no restart.
 *
 * **This file is the whole of compose's routing.** Traefik runs no other provider: the Docker provider needs the
 * Docker socket, and a `:ro` mount of it restricts nothing about the API, so the internet-facing proxy would hold
 * root on the host. Everything a router references — services, middlewares — is therefore defined here, in the
 * same atomic write, and referenced without a provider suffix so the name resolves inside this file.
 *
 * The write is temp-file-plus-atomic-rename because Traefik watches this directory and reloads on change: a
 * plain truncate-and-write is observable as a **half-written file**, which Traefik parses and rejects, dropping
 * every router until the next regenerate — the bootstrap domain's included, since it lives here too.
 *
 * [bootstrapDomain] and [adminDomain] are already lowercased, validated hostnames or `null`
 * (`TenantIngressSinkProducer`); a `null` bootstrap domain was already logged there as the misconfiguration it is.
 */
class TraefikFileIngressSink(
    private val target: Path,
    private val bootstrapDomain: String?,
    private val adminDomain: String?,
    private val upstreams: Upstreams,
    /** `veyq.blob-store.bucket`, already refused by `BlobStoreStartupCheck` unless it is a valid S3 bucket name. */
    bucket: String,
) : TenantIngressSink {

    /**
     * The blobs route is the bucket's path, derived and never spelled (ADR 0013 §4): path-style presigning puts
     * every object at `/<bucket>/<key>`, so a literal serves the default bucket and 404s every other one. The
     * trailing slash is load-bearing — Traefik's `PathPrefix` is a raw string prefix, and without it the store
     * would also claim every app path that merely begins with the bucket's name.
     */
    private val blobsPrefix = "/$bucket/"

    /** Where the rendered services point — the recipe's topology, passed in as configuration (ADR 0063). */
    data class Upstreams(val app: String, val blobs: String, val admin: String)

    override val enabled = true

    override fun apply(domains: List<String>) {
        writeAtomically(target, render(domains))
    }

    /**
     * The complete dynamic configuration: every router pair (the bootstrap domain's from configuration, then one
     * per tenant domain in [domains]), the admin router when an admin domain is configured, and the services and
     * middleware they reference.
     *
     * Every domain gets byte-for-byte the same pair, which is what keeps ADR 0013 §4's same-origin,
     * prefix-preserved blob route true for every tenant and not just the first: the blobs router carries the
     * higher priority because its rule is the longer one and must win over the catch-all app router, and its
     * service keeps `passHostHeader` because SigV4 signs the host. Every blobs router also carries
     * `veyq-blobs-inert` (ADR 0013 §6): the store shares the app's origin here, so a store response must never
     * render as a page on it.
     *
     * `internal` rather than private so `TenantIngressEmptyProjectionTest` can call it with an explicit domain
     * list. The alternative — driving it through [TenantIngressProjector.regenerate] — cannot reach every state:
     * the `%test` H2 instance is shared across test profiles and already carries tenant rows with a
     * `veyq_membership` foreign key, so "no tenant rows" is a state no test can reach by deleting. This is a pure
     * function of its argument, and the DB half it would otherwise exercise is `TenantIngressProjectorTest`'s
     * subject.
     */
    internal fun render(domains: List<String>): String = buildString {
        append("# GENERATED by veyq's TenantIngressProjector from configuration and the `tenant` table (ADR 0063).\n")
        append("# Do not edit: every write is a full regenerate and will discard your changes.\n")
        append("http:\n")
        val routed = listOfNotNull(bootstrapDomain) + domains
        if (routed.isNotEmpty() || adminDomain != null) {
            // Only when there is a router to put in it. Traefik rejects a section that is present but empty —
            // `routers: {}` fails with "routers cannot be a standalone element" (measured on the pinned v3.6, see
            // TenantIngressEmptyProjectionTest) — and with no bootstrap domain and no tenant this one would be.
            append("  routers:\n")
            routed.forEach { domain ->
                // The bootstrap pair is `veyq-app`/`veyq-blobs`; a tenant's is named after its domain,
                // not its position, so adding some other tenant never churns every router in the dashboard and
                // logs. The hostname shape the projector validated is exactly what a router name allows, and the
                // `veyq-tenant-` prefix keeps a tenant's name from ever colliding with the bootstrap pair's.
                val name = if (domain == bootstrapDomain) "veyq" else "veyq-tenant-${domain.replace('.', '-')}"
                router("$name-app", "Host(`$domain`)", priority = 1, service = APP)
                router("$name-blobs", "Host(`$domain`) && PathPrefix(`$blobsPrefix`)", priority = 100, service = BLOBS, middleware = INERT)
            }
            adminDomain?.let { router(ADMIN, "Host(`$it`)", priority = null, service = ADMIN) }
        }
        append("  services:\n")
        service(APP, upstreams.app, passHostHeader = false)
        service(BLOBS, upstreams.blobs, passHostHeader = true)
        service(ADMIN, upstreams.admin, passHostHeader = false)
        append("  middlewares:\n")
        append("    $INERT:\n")
        append("      headers:\n")
        append("        contentTypeNosniff: true\n")
        append("        contentSecurityPolicy: \"sandbox; default-src 'none'\"\n")
    }

    /** No prefix strip and the `Host` preserved, on every router: SigV4 signs host+path, so either rewrite breaks every presigned URL. */
    private fun StringBuilder.router(name: String, rule: String, priority: Int?, service: String, middleware: String? = null) {
        append("    $name:\n")
        append("      rule: \"$rule\"\n")
        priority?.let { append("      priority: $it\n") }
        append("      entryPoints: [websecure]\n")
        append("      service: $service\n")
        middleware?.let { append("      middlewares: [$it]\n") }
        append("      tls:\n")
        append("        certResolver: letsencrypt\n")
    }

    private fun StringBuilder.service(name: String, url: String, passHostHeader: Boolean) {
        append("    $name:\n")
        append("      loadBalancer:\n")
        if (passHostHeader) append("        passHostHeader: true\n")
        append("        servers:\n")
        append("          - url: \"$url\"\n")
    }

    /**
     * **Every filesystem call is inside the `try`, and that boundary is the point of this function.** It used
     * to start one line lower, with `createDirectories` and `createTempFile` above it — and an unwritable
     * directory throws on exactly those two, so the `AccessDeniedException` that a root-owned volume produced
     * went straight past the catch below. From `TenantIngressProjector.onStartup` that failed the Quarkus
     * startup event and the container restart-looped: an instance that could not project its routing would not
     * serve `/api/setup` either. The directory ownership that caused it is fixed in the `Dockerfile` and held by
     * `scripts/validate_app_volume_ownership.py`, but only for the compose deployment that guard can read —
     * ADR 0064's chart brings its own volume semantics, so degrading here is the half that travels.
     * `TenantIngressUnwritablePathTest` bites both callers.
     */
    private fun writeAtomically(target: Path, content: String) {
        var tmp: Path? = null
        try {
            val dir = target.toAbsolutePath().parent
            Files.createDirectories(dir)
            // Same directory as the target on purpose: an ATOMIC_MOVE is only guaranteed within one filesystem.
            tmp = Files.createTempFile(dir, ".${target.fileName}", ".tmp")
            // `createTempFile` makes the file 0600 and the rename keeps that mode, but the READER is Traefik, under
            // a uid of its own (ADR 0071). A file it cannot open is a file provider that fails to start while the
            // proxy stays up and routes nothing (measured on traefik:v3.6 as uid 65532: "error adding file watcher
            // … permission denied"). World-readable is safe: this is routing config, never a secret (ADR 0063).
            if ("posix" in dir.fileSystem.supportedFileAttributeViews()) {
                Files.setPosixFilePermissions(tmp, PosixFilePermissions.fromString("rw-r--r--"))
            }
            Files.writeString(tmp, content)
            Files.move(tmp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE)
        } catch (e: Exception) {
            // Best-effort, and swallowed on purpose: the cleanup runs in the very state that got us here, so on
            // an unwritable directory `deleteIfExists` throws too — out of the catch block, past every caller,
            // and the degrade this function exists for would be undone by its own tidying.
            tmp?.let { runCatching { Files.deleteIfExists(it) } }
            // A failed projection must not fail the tenant operation that triggered it: the row is committed and
            // correct, and the next regenerate (any later mutation, or the next startup) repairs the file. Loud,
            // because until then the new domain does not resolve.
            log.errorf(e, "Could not write the tenant ingress projection to %s — routing is stale until the next regenerate", target)
        }
    }

    private companion object {
        val log: Logger = Logger.getLogger(TraefikFileIngressSink::class.java)
        const val APP = "veyq-app"
        const val BLOBS = "veyq-blobs"
        const val ADMIN = "veyq-admin"
        const val INERT = "veyq-blobs-inert"
    }
}
