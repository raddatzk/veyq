const KNOWN = new Set(RECIPIENT_COUNTRIES)

/** [typed] as the code the backend takes — upper-cased, null where it is no code of the list. */
export function countryCode(typed: string): string | null {
  const code = typed.trim().toUpperCase()
  return KNOWN.has(code) ? code : null
}

/** The countries as a select offers them: the code as the value, its name in [locale] as the label, sorted by name. */
export function countryOptions(locale: string): { value: string; label: string }[] {
  const names = new Intl.DisplayNames([locale], { type: 'region', fallback: 'code' })
  const collator = new Intl.Collator(locale)
  return RECIPIENT_COUNTRIES.map((code) => ({ value: code, label: names.of(code) ?? code }))
    .sort((a, b) => collator.compare(a.label, b.label))
}
