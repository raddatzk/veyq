import { ref, watch, type Ref } from 'vue'

export const SUPPORTED_LOCALES: SupportedLocale[] = ['en', 'de']
// Endonyms — a language is named in its own tongue regardless of the current UI locale.
export const LOCALE_LABELS: Record<SupportedLocale, string> = { en: 'English', de: 'Deutsch' }

/** The user's language choice: a concrete language, or "system" — follow the OS (the default). */
export type LocalePreference = 'system' | SupportedLocale
export const LOCALE_PREFERENCES: LocalePreference[] = ['system', 'en', 'de']

const LOCALE_STORAGE_KEY = 'veyq:locale'

function storage(): Storage | null {
  try {
    return typeof window !== 'undefined' ? window.localStorage : null
  } catch {
    return null
  }
}

/** The OS language mapped onto a supported locale (anything not German → English). */
function systemLocale(): SupportedLocale {
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'en'
  return nav.startsWith('de') ? 'de' : 'en'
}

function storedPreference(): LocalePreference {
  const stored = storage()?.getItem(LOCALE_STORAGE_KEY)
  return stored === 'en' || stored === 'de' || stored === 'system' ? stored : 'system'
}

/** The active locale for a preference — "system" resolves to the OS language. */
export function effectiveLocale(pref: LocalePreference): SupportedLocale {
  return pref === 'system' ? systemLocale() : pref
}

// The reactive language preference (mirrors `useThemeState`'s `themePreference`) — default "system".
const localePref = ref<LocalePreference>(storedPreference())
/** The reactive language preference ("system" | "en" | "de"). */
export function localePreference(): Ref<LocalePreference> {
  return localePref
}

export const i18n = createI18n({
  legacy: false,
  locale: effectiveLocale(localePref.value),
  fallbackLocale: 'en',
  messages: { en, de },
})

/** An application's message catalog: its own top-level namespaces, in every supported locale. */
export type ApplicationMessages = Record<SupportedLocale, Record<string, unknown>>

/**
 * Add an application's catalog to the one instance (ADR 0079, inbox #513). The catalog above is core's alone; each
 * application keeps its namespaces in its own directory (`features/<owner>/i18n.ts`), and the composition root's
 * catalog half (`src/web/src/applicationMessages.ts`) hands them here, by static import — core never imports one.
 * **Write-once**, like the registry: a namespace someone already holds (core's, or another application's) THROWS and
 * nothing is added, so an application can neither overwrite `node.*` nor take over another's strings; and a catalog
 * whose locales carry different namespaces throws too (`typeof en` holds the keys below a namespace to EN's).
 */
export function addApplicationMessages(owner: string, messages: ApplicationMessages): void {
  const [first, ...rest] = SUPPORTED_LOCALES.map((l) => Object.keys(messages[l]).sort().join(','))
  if (rest.some((names) => names !== first)) {
    throw new Error(`The ${owner} catalog carries different namespaces per locale: ${SUPPORTED_LOCALES.map((l) => `${l}: ${Object.keys(messages[l]).join(', ')}`).join('; ')}`)
  }
  for (const locale of SUPPORTED_LOCALES) {
    const held = i18n.global.getLocaleMessage(locale) as Record<string, unknown>
    const taken = Object.keys(messages[locale]).filter((ns) => ns in held)
    if (taken.length) throw new Error(`The ${owner} catalog names a namespace someone already holds: ${taken.join(', ')} (${locale})`)
  }
  for (const locale of SUPPORTED_LOCALES) i18n.global.mergeLocaleMessage(locale, messages[locale])
}

// The document's language follows the UI's (inbox #395): `index.html` ships `lang="en"`, and a screen reader, the
// browser's hyphenation and its translate offer read `<html lang>` — set at start and on every switch.
watch(
  i18n.global.locale,
  (locale) => {
    if (typeof document !== 'undefined') document.documentElement.lang = locale
  },
  { immediate: true, flush: 'sync' },
)

/** Set the language preference (a concrete language, or "system") and remember it. */
export function setLocalePreference(pref: LocalePreference): void {
  localePref.value = pref
  storage()?.setItem(LOCALE_STORAGE_KEY, pref)
  i18n.global.locale.value = effectiveLocale(pref)
}

// Live-follow the OS language while on "system" — the browser fires `languagechange` when it changes.
if (typeof window !== 'undefined') {
  window.addEventListener('languagechange', () => {
    if (localePref.value === 'system') i18n.global.locale.value = systemLocale()
  })
}
