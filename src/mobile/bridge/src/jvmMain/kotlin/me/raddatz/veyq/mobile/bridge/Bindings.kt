/**
 * The wire's types as the serial descriptors give them (ADR 0123's Consequences, the bridge): every class, sealed class and
 * enum reachable from [Roots], each with its fields. [Bindings.rust] writes the Linux host's Rust from it and
 * [Bindings.csharp] the Windows host's C#, and the tests read the same walk — what is generated is what is checked.
 */
internal class Schema(roots: List<KSerializer<*>>) {
    /** A type the wire names, by its serial name (without a nullable's `?`). */
    class Type(val serialName: String, val descriptor: SerialDescriptor) {
        val kind: SerialKind get() = descriptor.kind
        val isSealed: Boolean get() = kind == PolymorphicKind.SEALED

        /** A sealed class's subclasses, each a variant tagged `type` with its serial name. */
        val variants: List<SerialDescriptor>
            get() = if (isSealed) descriptor.getElementDescriptor(1).elementDescriptors.toList() else emptyList()
    }

    /** One field of a class or a sealed variant: [owner] is its class's serial name. */
    class Field(val owner: String, val name: String, val descriptor: SerialDescriptor)

    val types = LinkedHashMap<String, Type>()
    val roots: List<Type>

    init {
        roots.forEach { visit(it.descriptor) }
        this.roots = roots.map { types.getValue(nameOf(it.descriptor)) }
    }

    private fun visit(d: SerialDescriptor) {
        when (d.kind) {
            StructureKind.LIST, StructureKind.MAP -> d.elementDescriptors.forEach(::visit)
            StructureKind.CLASS, StructureKind.OBJECT, SerialKind.ENUM, PolymorphicKind.SEALED -> {
                val name = nameOf(d)
                if (name in types) return
                val t = Type(name, d)
                types[name] = t
                if (t.isSealed) t.variants.forEach { v -> v.elementDescriptors.forEach(::visit) }
                else if (d.kind != SerialKind.ENUM) d.elementDescriptors.forEach(::visit)
            }
            is PrimitiveKind -> {}
            else -> error("${d.serialName}: a ${d.kind} has no form on the wire (an open polymorphic or contextual type)")
        }
    }

    /** Every field of [t]: a class's own, or each variant's of a sealed class. */
    fun fields(t: Type): List<Field> = when {
        t.isSealed -> t.variants.flatMap { v -> fieldsOf(v, v.serialName) }
        t.kind == SerialKind.ENUM -> emptyList()
        else -> fieldsOf(t.descriptor, t.serialName)
    }

    private fun fieldsOf(d: SerialDescriptor, owner: String) = (0 until d.elementsCount).map { Field(owner, d.getElementName(it), d.getElementDescriptor(it)) }

    /** Every type reachable from [from], [from] among them. */
    fun reachable(from: Type): Set<Type> {
        val seen = LinkedHashSet<Type>()
        fun go(t: Type) {
            if (!seen.add(t)) return
            fields(t).forEach { f -> typesIn(f.descriptor).forEach(::go) }
        }
        go(from)
        return seen
    }

    private fun typesIn(d: SerialDescriptor): List<Type> = when (d.kind) {
        StructureKind.LIST, StructureKind.MAP -> d.elementDescriptors.flatMap(::typesIn)
        is PrimitiveKind -> emptyList()
        else -> listOf(types.getValue(nameOf(d)))
    }

    /** Whether [from] holds [to] directly — through fields, never through a list or a map — so Rust must box it. */
    fun holdsDirectly(from: Type, to: Type): Boolean {
        val seen = HashSet<String>()
        fun go(t: Type): Boolean {
            if (!seen.add(t.serialName)) return false
            return fields(t).any { f ->
                val d = f.descriptor
                d.kind !is PrimitiveKind && d.kind != StructureKind.LIST && d.kind != StructureKind.MAP && d.kind != SerialKind.ENUM &&
                    types.getValue(nameOf(d)).let { it == to || go(it) }
            }
        }
        return go(from)
    }

    companion object {
        fun nameOf(d: SerialDescriptor) = d.serialName.removeSuffix("?")
    }
}

/**
 * The hosts' half of the wire: Rust's serde types and C#'s System.Text.Json records, each with the wire's field names
 * and the six functions of `bridge.h`. Both name a type by [rustNames] (the samples' file names are those names).
 */
internal object Bindings {
    fun rust(schema: Schema, header: String): String {
        val names = rustNames(schema.types.keys)
        val out = StringBuilder()
        out.append(
            """
            |// Generated by `./gradlew :bridge:generateBindings` from the core's serial descriptors and bridge.h
            |// (ADR 0123's Consequences, the bridge). Never edited, never committed: change the Kotlin type or the header instead.
            |// Included into a module of the host's (`include!`), which carries the lints' allowances: an included file may
            |// hold no inner attribute.
            |
            |use serde::{Deserialize, Serialize};
            |
            |""".trimMargin(),
        )
        for ((serialName, t) in schema.types.toSortedMap()) {
            val name = names.getValue(serialName)
            out.append("/// `$serialName`\n")
            when {
                t.kind == SerialKind.ENUM -> {
                    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]\npub enum $name {\n")
                    (0 until t.descriptor.elementsCount).forEach { i ->
                        val entry = t.descriptor.getElementName(i)
                        out.append("    #[serde(rename = \"$entry\")]\n    ${pascal(entry)},\n")
                    }
                    out.append("}\n\n")
                }
                t.isSealed -> {
                    out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(tag = \"type\")]\npub enum $name {\n")
                    t.variants.forEach { v ->
                        out.append("    #[serde(rename = \"${v.serialName}\")]\n    ${pascal(v.serialName)}")
                        if (v.elementsCount == 0) out.append(",\n")
                        else {
                            out.append(" {\n")
                            (0 until v.elementsCount).forEach { i -> out.append(field(schema, names, t, v.getElementName(i), v.getElementDescriptor(i), "        ", visibility = "")) }
                            out.append("    },\n")
                        }
                    }
                    out.append("}\n\n")
                }
                else -> {
                    out.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\npub struct $name {\n")
                    (0 until t.descriptor.elementsCount).forEach { i -> out.append(field(schema, names, t, t.descriptor.getElementName(i), t.descriptor.getElementDescriptor(i), "    ")) }
                    out.append("}\n\n")
                }
            }
        }
        out.append(reserialize(names))
        out.append(externs(header))
        return out.toString()
    }

    /**
     * `reserialize(type, json)`: reads [json] as the wire type whose Rust name is `type` and writes it back — the door
     * of the host's round-trip test over the samples the JVM wrote. Generated with the types, so every type has its
     * case and a sample of a type the host does not have reads as None (red), never as a list kept in a test.
     */
    private fun reserialize(names: Map<String, String>): String {
        val out = StringBuilder(
            """
            |/// Reads `json` as the wire type named `rust_type` and writes it back as JSON; None for a name no wire type has.
            |pub fn reserialize(rust_type: &str, json: &str) -> Option<serde_json::Result<serde_json::Value>> {
            |    fn go<T: serde::de::DeserializeOwned + Serialize>(json: &str) -> serde_json::Result<serde_json::Value> {
            |        serde_json::from_str::<T>(json).and_then(|v| serde_json::to_value(&v))
            |    }
            |    Some(match rust_type {
            |
            """.trimMargin(),
        )
        names.values.sorted().forEach { out.append("        \"$it\" => go::<$it>(json),\n") }
        out.append("        _ => return None,\n    })\n}\n\n")
        return out.toString()
    }

    /** A field; a sealed variant's takes no `pub` (Rust gives an enum's fields its visibility). */
    private fun field(schema: Schema, names: Map<String, String>, owner: Schema.Type, name: String, d: SerialDescriptor, indent: String, visibility: String = "pub "): String {
        val rustName = snake(name)
        val rename = if (rustName.removePrefix("r#") != name) "$indent#[serde(rename = \"$name\")]\n" else ""
        return "$rename$indent$visibility$rustName: ${type(schema, names, owner, d, direct = true)},\n"
    }

    /** [d]'s Rust type in [owner]; a [direct] field (not a list's or a map's element) that holds [owner] again is boxed. */
    private fun type(schema: Schema, names: Map<String, String>, owner: Schema.Type, d: SerialDescriptor, direct: Boolean): String {
        val base = when (val k = d.kind) {
            PrimitiveKind.STRING -> "String"
            PrimitiveKind.INT -> "i32"
            PrimitiveKind.LONG -> "i64"
            PrimitiveKind.SHORT -> "i16"
            PrimitiveKind.BYTE -> "i8"
            PrimitiveKind.BOOLEAN -> "bool"
            PrimitiveKind.DOUBLE -> "f64"
            PrimitiveKind.FLOAT -> "f32"
            PrimitiveKind.CHAR -> "char"
            StructureKind.LIST -> "Vec<${type(schema, names, owner, d.getElementDescriptor(0), direct = false)}>"
            StructureKind.MAP -> "std::collections::BTreeMap<${type(schema, names, owner, d.getElementDescriptor(0), direct = false)}, ${type(schema, names, owner, d.getElementDescriptor(1), direct = false)}>"
            else -> {
                val t = schema.types[Schema.nameOf(d)] ?: error("${d.serialName}: not walked ($k)")
                val n = names.getValue(t.serialName)
                if (direct && t.kind != SerialKind.ENUM && (t == owner || schema.holdsDirectly(t, owner))) "Box<$n>" else n
            }
        }
        return if (d.isNullable) "Option<$base>" else base
    }

    /** Each type's Rust name: its serial name's last part, or its last two where that part is taken twice. */
    fun rustNames(serialNames: Collection<String>): Map<String, String> {
        fun last(n: Int, s: String) = s.split('.').takeLast(n).joinToString("") { pascal(it) }
        val byLast = serialNames.groupBy { last(1, it) }
        val names = serialNames.associateWith { s -> if (byLast.getValue(last(1, s)).size == 1) last(1, s) else last(2, s) }
        val clash = names.values.groupBy { it }.filterValues { it.size > 1 }.keys
        check(clash.isEmpty()) { "two wire types would share the Rust name ${clash.joinToString()}" }
        return names.mapValues { (_, n) -> if (n in RESERVED) "Veyq$n" else n }
    }

    /** `Session.SignIn` → `SessionSignIn`, `DEVICE_KEY` → `DeviceKey`, `said` → `Said`. */
    fun pascal(s: String): String = s.split('.', '_', '-').filter { it.isNotEmpty() }.joinToString("") { part ->
        if (part.all { !it.isLetter() || it.isUpperCase() }) part.lowercase().replaceFirstChar { it.uppercase() } else part.replaceFirstChar { it.uppercase() }
    }

    /** `connectionKey` → `connection_key`; a Rust keyword is raw (`r#ref`). */
    fun snake(s: String): String {
        val n = s.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").lowercase()
        return if (n in KEYWORDS) "r#$n" else n
    }

    private val RESERVED = setOf("Option", "Result", "String", "Vec", "Box", "Self")
    private val KEYWORDS = setOf(
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn", "for", "gen",
        "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait",
        "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro", "override",
        "priv", "try", "typeof", "unsized", "virtual", "yield",
    )

    // ---- bridge.h ----

    /** A C declaration of bridge.h: a function, or a function-pointer typedef. */
    class Decl(val name: String, val returns: String, val params: List<Pair<String, String>>)

    /** bridge.h's typedefs and functions, as written there (`int32_t veyq_init(const char *config, …);`). */
    fun parseHeader(header: String): Pair<List<Decl>, List<Decl>> {
        val text = header.replace(Regex("/\\*.*?\\*/", RegexOption.DOT_MATCHES_ALL), " ").replace(Regex("\\s+"), " ")
        fun params(p: String) = p.trim().takeUnless { it == "void" || it.isEmpty() }?.split(',')?.map { one ->
            val m = Regex("^(.*?)(\\w+)$").find(one.trim()) ?: error("a parameter without a name: $one")
            m.groupValues[1].trim() to m.groupValues[2]
        }.orEmpty()
        val statements = text.split(';').map { it.trim() }
        val typedefs = statements.mapNotNull { Regex("typedef ([\\w\\s*]+?)\\s*\\(\\s*\\*\\s*(\\w+)\\s*\\)\\s*\\(([^)]*)\\)$").find(it) }
            .map { Decl(it.groupValues[2], it.groupValues[1].trim(), params(it.groupValues[3])) }
        val functions = statements.filterNot { "typedef" in it }.mapNotNull { Regex("(\\w+(?:\\s*\\*)?)\\s+(veyq_\\w+)\\s*\\(([^)]*)\\)$").find(it) }
            .map { Decl(it.groupValues[2], it.groupValues[1].trim(), params(it.groupValues[3])) }
        return typedefs to functions
    }

    private fun rustC(c: String, typedefs: Set<String>): String = when (val t = c.replace(Regex("\\s+"), " ").replace(" *", "*").trim()) {
        "void" -> "()"
        "int32_t" -> "i32"
        "uint64_t" -> "u64"
        "size_t" -> "usize"
        "const char*" -> "*const std::ffi::c_char"
        "const uint8_t*" -> "*const u8"
        "void*" -> "*mut std::ffi::c_void"
        in typedefs -> pascal(t)
        else -> error("bridge.h: no Rust type for `$c`")
    }

    private fun externs(header: String): String {
        val (typedefs, functions) = parseHeader(header)
        val names = typedefs.map { it.name }.toSet()
        fun sig(d: Decl) = d.params.joinToString(", ") { (t, n) -> "$n: ${rustC(t, names)}" } +
            ")" + rustC(d.returns, names).let { if (it == "()") "" else " -> $it" }
        val out = StringBuilder("// ---- bridge.h ----\n\n")
        typedefs.forEach { out.append("pub type ${pascal(it.name)} = unsafe extern \"C\" fn(${sig(it)};\n") }
        out.append("\nunsafe extern \"C\" {\n")
        functions.forEach { out.append("    pub fn ${it.name}(${sig(it)};\n") }
        out.append("}\n")
        if (typedefs.any(::carriesPayload)) {
            out.append(
                """
                |
                |/// The payload a callback is handed beside its JSON (bridge.h's `bytes`, `len`) as the `Option<&[u8]>` it is,
                |/// copied into a `Vec<u8>` before the callback returns: the core's pointer is valid only during the call. None
                |/// where the core passed none (NULL): every answer but `Answer::Bytes`, every update, every host request.
                |///
                |/// # Safety
                |/// `bytes` is NULL, or points at `len` bytes readable for the duration of this call.
                |pub unsafe fn payload(bytes: *const u8, len: usize) -> Option<Vec<u8>> {
                |    // SAFETY: the caller's: NULL, or `len` readable bytes.
                |    let shown: Option<&[u8]> = if bytes.is_null() { None } else { Some(unsafe { std::slice::from_raw_parts(bytes, len) }) };
                |    shown.map(<[u8]>::to_vec)
                |}
                |""".trimMargin(),
            )
        }
        return out.toString()
    }

    /** Whether a callback of bridge.h is handed a payload beside its JSON: a `const uint8_t *` followed by its `size_t`. */
    private fun carriesPayload(d: Decl): Boolean = d.params.zipWithNext().any { (a, b) ->
        a.first.replace(" ", "") == "constuint8_t*" && b.first.trim() == "size_t"
    }

    // ---- C# (the Windows host, ADR 0123's Consequences, the bridge) ----

    private const val CS = "global::Veyq.Bridge.Wire"
    private const val STJ = "global::System.Text.Json.Serialization"

    /**
     * The C# half of the wire, `Bridge.g.cs`: a `record` per class with its fields under their serial names; an
     * `abstract record` per sealed class, tagged `type`, its variants nested in it; an enum per enum with each entry's
     * serial name; a source-generated `JsonSerializerContext` over every type (reflection-free); `Reserialize`, the round
     * trip's door; and the six functions of `bridge.h` as `[LibraryImport("veyq")]`. Every type is named from `global::`,
     * since a variant nested in its sealed class may share its name with a type of the wire (`Update.Shell`, `Shell`).
     * Every field is `required`: the wire writes every one (`explicitNulls`, `encodeDefaults`), so a missing one is a
     * defect, and a field the type does not know is refused (`UnmappedMemberHandling.Disallow`).
     */
    fun csharp(schema: Schema, header: String): String {
        val names = rustNames(schema.types.keys)
        val out = StringBuilder()
        out.append(
            """
            |// <auto-generated>
            |// Generated by `./gradlew :bridge:generateBindings` from the core's serial descriptors and bridge.h
            |// (ADR 0123's Consequences, the bridge). Never edited, never committed: change the Kotlin type or the header instead.
            |// </auto-generated>
            |#nullable enable
            |
            |""".trimMargin(),
        )
        out.append(csAliases(header))
        out.append("\nnamespace Veyq.Bridge.Wire;\n\n")
        for ((serialName, t) in schema.types.toSortedMap()) {
            val name = names.getValue(serialName)
            out.append("/// <summary><c>$serialName</c></summary>\n")
            when {
                t.kind == SerialKind.ENUM -> {
                    out.append("[$STJ.JsonConverter(typeof($STJ.JsonStringEnumConverter<$CS.$name>))]\npublic enum $name\n{\n")
                    (0 until t.descriptor.elementsCount).forEach { i ->
                        val entry = t.descriptor.getElementName(i)
                        out.append("    [$STJ.JsonStringEnumMemberName(\"$entry\")] ${pascal(entry)},\n")
                    }
                    out.append("}\n\n")
                }
                t.isSealed -> {
                    out.append("[$STJ.JsonPolymorphic(TypeDiscriminatorPropertyName = \"type\")]\n")
                    t.variants.forEach { v -> out.append("[$STJ.JsonDerivedType(typeof($CS.$name.${pascal(v.serialName)}), \"${v.serialName}\")]\n") }
                    out.append("public abstract record $name\n{\n    private $name() { }\n")
                    t.variants.forEach { v ->
                        out.append("\n    /// <summary><c>${v.serialName}</c></summary>\n")
                        out.append("    public sealed record ${pascal(v.serialName)} : $CS.$name")
                        if (v.elementsCount == 0) out.append(";\n")
                        else {
                            out.append("\n    {\n")
                            (0 until v.elementsCount).forEach { i -> out.append(csField(schema, names, pascal(v.serialName), v.getElementName(i), v.getElementDescriptor(i), "        ")) }
                            out.append("    }\n")
                        }
                    }
                    out.append("}\n\n")
                }
                else -> {
                    out.append("public sealed record $name\n{\n")
                    (0 until t.descriptor.elementsCount).forEach { i -> out.append(csField(schema, names, name, t.descriptor.getElementName(i), t.descriptor.getElementDescriptor(i), "    ")) }
                    out.append("}\n\n")
                }
            }
        }
        out.append(csContext(schema, names))
        out.append(csExterns(header))
        return out.toString()
    }

    /**
     * A property of [owner] named as the field's serial name, which it also carries as its JSON name; a C# keyword is
     * Pascal-cased instead (`ref` → `Ref`: an `@ref` property breaks System.Text.Json's source generator, measured
     * 2026-11-10 with SDK 10.0.301, CS1525 in its output). Pascal names alone would collide: a property may not be named
     * as its class (`Update.Pot`'s `pot`).
     */
    private fun csField(schema: Schema, names: Map<String, String>, owner: String, name: String, d: SerialDescriptor, indent: String): String {
        val property = if (name in CS_KEYWORDS) pascal(name) else name
        check(property != owner) { "$owner.$name: a C# property may not be named as its class" }
        return "$indent[$STJ.JsonPropertyName(\"$name\")] public required ${csType(schema, names, d)} $property { get; init; }\n"
    }

    private fun csType(schema: Schema, names: Map<String, String>, d: SerialDescriptor): String {
        val base = when (val k = d.kind) {
            PrimitiveKind.STRING -> "string"
            PrimitiveKind.INT -> "int"
            PrimitiveKind.LONG -> "long"
            PrimitiveKind.SHORT -> "short"
            PrimitiveKind.BYTE -> "sbyte"
            PrimitiveKind.BOOLEAN -> "bool"
            PrimitiveKind.DOUBLE -> "double"
            PrimitiveKind.FLOAT -> "float"
            PrimitiveKind.CHAR -> "char"
            StructureKind.LIST -> "global::System.Collections.Generic.IReadOnlyList<${csType(schema, names, d.getElementDescriptor(0))}>"
            StructureKind.MAP -> "global::System.Collections.Generic.IReadOnlyDictionary<${csType(schema, names, d.getElementDescriptor(0))}, ${csType(schema, names, d.getElementDescriptor(1))}>"
            else -> {
                val t = schema.types[Schema.nameOf(d)] ?: error("${d.serialName}: not walked ($k)")
                "$CS.${names.getValue(t.serialName)}"
            }
        }
        return if (d.isNullable) "$base?" else base
    }

    /**
     * The source-generated context over every type, and `Reserialize(type, json)`: reads [json] as the wire type whose
     * name is `type` and writes it back — the door of the host's round-trip test over the samples the JVM wrote, as the
     * Rust `reserialize` is. Null for a name no wire type has, so a sample of a type the host lacks is red.
     */
    private fun csContext(schema: Schema, names: Map<String, String>): String {
        val sorted = names.values.sorted()
        // Each variant under its sealed class's name and its own: the generator names a type's metadata by its simple
        // name, which variants of different sealed classes share (`Answer.Done`, `HostReply.Done`; SYSLIB1031).
        val variants = schema.types.values.filter { it.isSealed }.flatMap { t ->
            t.variants.map { v -> "${names.getValue(t.serialName)}.${pascal(v.serialName)}" to names.getValue(t.serialName) + pascal(v.serialName) }
        }
        val clash = (sorted + variants.map { it.second }).groupBy { it }.filterValues { it.size > 1 }.keys
        check(clash.isEmpty()) { "two C# metadata names would be one: ${clash.joinToString()}" }
        val out = StringBuilder()
        out.append(
            """
            |/// <summary>The wire's System.Text.Json metadata, generated at build time: no reflection.</summary>
            |[$STJ.JsonSourceGenerationOptions(
            |    RespectNullableAnnotations = true,
            |    UnmappedMemberHandling = global::System.Text.Json.Serialization.JsonUnmappedMemberHandling.Disallow)]
            |
            """.trimMargin(),
        )
        sorted.forEach { out.append("[$STJ.JsonSerializable(typeof($CS.$it))]\n") }
        variants.forEach { (type, info) -> out.append("[$STJ.JsonSerializable(typeof($CS.$type), TypeInfoPropertyName = \"$info\")]\n") }
        out.append("public sealed partial class WireContext : global::System.Text.Json.Serialization.JsonSerializerContext\n{\n}\n\n")
        out.append(
            """
            |/// <summary>The round trip's door.</summary>
            |public static class WireTypes
            |{
            |    /// <summary>Reads <paramref name="json"/> as the wire type named <paramref name="type"/> and writes it back; null for a name no wire type has.</summary>
            |    public static string? Reserialize(string type, string json) => type switch
            |    {
            |
            """.trimMargin(),
        )
        sorted.forEach { out.append("        \"$it\" => Go(json, $CS.WireContext.Default.$it),\n") }
        out.append(
            """
            |        _ => null,
            |    };
            |
            |    private static string Go<T>(string json, global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T> info) =>
            |        global::System.Text.Json.JsonSerializer.Serialize(
            |            global::System.Text.Json.JsonSerializer.Deserialize(json, info) ?? throw new global::System.Text.Json.JsonException("null"), info);
            |}
            |
            |
            """.trimMargin(),
        )
        return out.toString()
    }

    private fun csC(c: String, typedefs: Set<String>): String = when (val t = c.replace(Regex("\\s+"), " ").replace(" *", "*").trim()) {
        "void" -> "void"
        "int32_t" -> "int"
        "uint64_t" -> "ulong"
        "size_t" -> "nuint"
        "const char*" -> "byte*"
        "const uint8_t*" -> "byte*"
        "void*" -> "void*"
        in typedefs -> pascal(t)
        else -> error("bridge.h: no C# type for `$c`")
    }

    /** bridge.h's typedefs as file-scoped aliases of unmanaged function pointers (C# names them nowhere else). */
    private fun csAliases(header: String): String {
        val (typedefs, _) = parseHeader(header)
        val names = typedefs.map { it.name }.toSet()
        return typedefs.joinToString("") { d ->
            "using unsafe ${pascal(d.name)} = delegate* unmanaged[Cdecl]<" +
                (d.params.map { csC(it.first, names) } + csC(d.returns, names)).joinToString(", ") + ">;\n"
        }
    }

    private fun csExterns(header: String): String {
        val (typedefs, functions) = parseHeader(header)
        val names = typedefs.map { it.name }.toSet()
        val out = StringBuilder("// ---- bridge.h ----\n\n")
        out.append("/// <summary>bridge.h's six functions, exported by veyq.dll.</summary>\n")
        out.append("public static unsafe partial class Native\n{\n")
        if (typedefs.any(::carriesPayload)) {
            out.append(
                """
                |    /// <summary>
                |    /// The payload a callback is handed beside its JSON (bridge.h's <c>bytes</c>, <c>len</c>) as the span it is, copied into
                |    /// a <c>byte[]</c> before the callback returns: the core's pointer is valid only during the call. Null where the core
                |    /// passed none (NULL): every answer but <c>Answer.Bytes</c>, every update, every host request.
                |    /// </summary>
                |    public static byte[]? Payload(byte* bytes, nuint len) =>
                |        bytes == null ? null : new global::System.ReadOnlySpan<byte>(bytes, checked((int)len)).ToArray();
                |
                |
                """.trimMargin(),
            )
        }
        functions.forEach { f ->
            val params = f.params.joinToString(", ") { (t, n) -> "${csC(t, names)} ${if (n in CS_KEYWORDS) "@$n" else n}" }
            out.append("    [global::System.Runtime.InteropServices.LibraryImport(\"veyq\")]\n")
            out.append("    [global::System.Runtime.InteropServices.UnmanagedCallConv(CallConvs = new[] { typeof(global::System.Runtime.CompilerServices.CallConvCdecl) })]\n")
            out.append("    public static partial ${csC(f.returns, names)} ${f.name}($params);\n\n")
        }
        out.append("}\n")
        return out.toString()
    }

    private val CS_KEYWORDS = setOf(
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    )
}

/** `generateBindings`: `<bridge.h> <output dir>` → `<output dir>/bridge.rs` and `<output dir>/Bridge.g.cs`. */
fun main(args: Array<String>) {
    val (header, outDir) = args
    val dir = File(outDir).apply { mkdirs() }
    val schema = Schema(Roots.all)
    val text = File(header).readText()
    dir.resolve("bridge.rs").apply { writeText(Bindings.rust(schema, text)) }.also { println("wrote $it") }
    dir.resolve("Bridge.g.cs").apply { writeText(Bindings.csharp(schema, text)) }.also { println("wrote $it") }
}
