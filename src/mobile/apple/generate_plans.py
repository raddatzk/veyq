#!/usr/bin/env python3
"""Generates the Swift form of every plan enum of the core (ADR 0154 decision 2; inbox #1050).

**Why.** A plan's enum (`@Plan` in the core, `navigation/Plan.kt`) reaches Swift through the Objective-C framework as a
class, not a Swift enum: a `switch` over it is never exhaustive and needs a `default:` to compile — the very fallback arm
`scripts/validate_mobile_structure.py` refuses, which would let an entry the core adds go undrawn. So each plan enum gets
an exhaustive Swift mirror, generated from the core before every build:

    extension HeaderAction {
        enum Entry: CaseIterable, Sendable { case favorite, share, …, theCopy, …, delete_, … }
        var entry: Entry { … }          // the core's entry as the mirror's (total: one case per entry, in its order)
    }
    extension HeaderAction.Entry { var core: HeaderAction { … } }   // and back

A drawing switches over `.entry` with no `default:`; an entry the core adds is a case here at the next build, and every
`switch` that forgot it fails to compile.

**Where the facts come from.** Which enums are plans, their entries and their order: the core's Kotlin sources, read by
the structure guard's own reader (`validate_mobile_structure.plan_enums`), so the guard and this mirror never disagree on
what a plan is. Each entry's Swift name: the framework's header (`--header`, the `VeyqCore.h` Kotlin/Native wrote for this
build), so Kotlin/Native's renames (`COPY` → `theCopy`, `DELETE` → `delete_`) are read, never re-derived. The two are
checked against each other — the same entries in the same order, else nothing is written and the build stops —, which is
what makes the mirror's ordinal mapping total.

Run by the Apple project's pre-build step after the framework is built (`project.yml`):
`python3 generate_plans.py --header <VeyqCore.h> --out build/generated/app/Plans.swift`.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "scripts"))
from validate_mobile_structure import PlanEnum, plan_enums  # noqa: E402

PREFIX = "VeyqCore"  # the framework's Objective-C prefix (composition/build.gradle.kts' baseName)


def _norm(name: str) -> str:
    """An entry's name with case and underscores gone: `OPEN_OWN_PAGE` and `openOwnPage`, `DELETE` and `delete_` meet
    (`COPY` and `theCopy` meet with the prefix `the`)."""
    return re.sub(r"_", "", name).lower()


def header_entries(header: str, plan: PlanEnum) -> list[str]:
    """The Swift names of [plan]'s entries as the header declares them, in its order."""
    objc = PREFIX + (plan.outer or "") + plan.name
    m = re.search(r"@interface\s+" + re.escape(objc) + r"\s*:\s*" + PREFIX + r"KotlinEnum<", header)
    if not m:
        raise SystemExit(f"generate_plans: `{objc}` is no Kotlin enum in the framework's header — is the framework current?")
    end = header.find("@end", m.end())
    body = header[m.end(): end]
    return re.findall(
        r"@property\s*\(class,\s*readonly\)\s*" + re.escape(objc) + r"\s*\*\s*\w+\s*__attribute__\(\(swift_name\(\"(\w+)\"\)\)\);",
        body,
    )


def swift_type(plan: PlanEnum) -> str:
    return f"{plan.outer}.{plan.name}" if plan.outer else plan.name


def render(plans: list[tuple[PlanEnum, list[str]]]) -> str:
    out = [
        "// Generated by src/mobile/apple/generate_plans.py from the core's @Plan enums and VeyqCore.h — never edited.",
        "// Each plan enum's exhaustive Swift form (ADR 0154 decision 2, inbox #1050): switch over `.entry`, never with `default:`.",
        "",
        "import VeyqCore",
    ]
    for plan, names in plans:
        t = swift_type(plan)
        out += [
            "",
            f"extension {t} {{",
            f"    /// `{t}`'s entries as a Swift enum, in the core's order: a `switch` over it is exhaustive.",
            "    enum Entry: CaseIterable, Sendable {",
            *(f"        case {n}" for n in names),
            "    }",
            "",
            "    /// This entry as the mirror's — by its ordinal, the two lists checked equal when this file was generated.",
            "    var entry: Entry {",
            "        let e = Entry.allCases[Int(ordinal)]",
            "        assert(e.core == self, \"Plans.swift is stale: regenerate it from the core\")",
            "        return e",
            "    }",
            "}",
            "",
            f"extension {t}.Entry {{",
            "    /// The core's entry.",
            f"    var core: {t} {{",
            "        switch self {",
            *(f"        case .{n}: {t}.{n}" for n in names),
            "        }",
            "    }",
            "}",
        ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--header", type=pathlib.Path, required=True, help="the framework's VeyqCore.h")
    ap.add_argument("--out", type=pathlib.Path, required=True, help="the Swift file to write")
    args = ap.parse_args(argv)
    header = args.header.read_text(encoding="utf-8")
    plans = [p for p in plan_enums() if p.name]
    if not plans:
        raise SystemExit("generate_plans: no @Plan enum read from the core")
    found: list[tuple[PlanEnum, list[str]]] = []
    for p in plans:
        names = header_entries(header, p)
        kotlin = [e for e, _ in p.entries]
        if len(names) != len(kotlin) or any(_norm(n) not in {_norm(k), "the" + _norm(k)} for n, k in zip(names, kotlin)):
            raise SystemExit(
                f"generate_plans: `{swift_type(p)}` differs between the core ({', '.join(kotlin)}) and the header "
                f"({', '.join(names)}) — rebuild the framework, or teach this generator the rename"
            )
        found.append((p, names))
    text = render(found)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
        args.out.write_text(text, encoding="utf-8")
    print(f"generate_plans: {len(found)} plan enums → {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
