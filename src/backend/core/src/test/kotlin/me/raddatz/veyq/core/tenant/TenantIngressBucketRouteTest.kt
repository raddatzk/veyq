package me.raddatz.veyq.core.tenant

import me.raddatz.veyq.core.blobstore.StoreSettingFixtures
import me.raddatz.veyq.core.testing.TestFixtures.seedTenant
import io.quarkus.test.junit.QuarkusTest
import io.quarkus.test.junit.QuarkusTestProfile
import io.quarkus.test.junit.TestProfile
import jakarta.inject.Inject
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import java.nio.file.Files
import java.nio.file.Path
import java.util.UUID

/**
 * **The same-origin blobs route follows the store in use** (ADR 0013 §4, ADR 0064 § the bundled store is opt-in,
 * ADR 0089 decision 5), driven through the producer's own sink and the real store setting, so a producer that hands
 * the sink the wrong lambda is caught as well as a sink that ignores it.
 *
 *  - **Only the bundled store, in use and offered, is routed** — on the bootstrap domain and every tenant domain,
 *    at exactly its bucket's path. A store of the operator's own has an origin of its own; with no store, or the
 *    bundled one chosen where the deployment passes no hint, a route would point at nothing — or serve an unused
 *    Garage's S3 API on every tenant domain. Each of those three negatives is read off the same file, regenerated by
 *    the same projector, as the bundled render that is its positive control.
 *  - **The bucket is derived, never spelled.** Presigned URLs are path-style, so an object's path is
 *    `/<bucket>/<key>`; the hint here carries a bucket that is not the default, which tells "derived from the store"
 *    apart from "happens to equal the default". The rule is compared whole, not searched for the bucket's name:
 *    `/restored-media` without the trailing slash would also contain it, and that is the prefix that claims every
 *    app path merely beginning with the name.
 *
 * Read at every render: the store changes after boot, and each step regenerates without a restart.
 */
@QuarkusTest
@TestProfile(TenantIngressBucketRouteTest.NonDefaultBucket::class)
class TenantIngressBucketRouteTest {

    class NonDefaultBucket : QuarkusTestProfile {
        override fun getConfigOverrides() = mapOf(
            "veyq.tenant.ingress.dynamic-config-path" to CONFIG_PATH,
            "veyq.tenant.ingress.bootstrap-domain" to BOOTSTRAP_DOMAIN,
        )
    }

    @Inject
    lateinit var projector: TenantIngressProjector

    @Test
    fun onlyTheBundledStoreInUseIsRoutedAndAtItsBucketsPathAlone() {
        val tenant = "b-${UUID.randomUUID()}.example.com"
        seedTenant(domain = tenant)
        try {
            StoreSettingFixtures.clear()
            projector.regenerate()
            assertNoBlobsRoute("no store set", tenant)

            StoreSettingFixtures.chooseS3(bucket = BUCKET)
            projector.regenerate()
            assertNoBlobsRoute("a store of the operator's own, even one whose bucket the bundled store would use", tenant)

            StoreSettingFixtures.chooseBundled()
            projector.regenerate()
            assertNoBlobsRoute("the bundled store chosen where the deployment passes no hint", tenant)

            // The positive control every negative above is read against: same sink, same file, same tenant.
            StoreSettingFixtures.useBundled(bucket = BUCKET)
            projector.regenerate()
            assertRoutesOnly(BUCKET, tenant)

            // …and the route goes when the store in use stops being the bundled one, with no restart.
            StoreSettingFixtures.chooseS3(bucket = BUCKET)
            projector.regenerate()
            assertNoBlobsRoute("after the bundled store was replaced", tenant)
        } finally {
            StoreSettingFixtures.clear()
        }
    }

    private fun assertNoBlobsRoute(state: String, tenant: String) {
        val file = Files.readString(Path.of(CONFIG_PATH))
        // Control: the file was rendered with both kinds of domain — the bootstrap pair's app router, from
        // configuration, and the projected tenant's. Without it, "no blobs router" holds of a file that routes nothing.
        assertTrue(file.contains("rule: \"Host(`$BOOTSTRAP_DOMAIN`)\"") && file.contains("rule: \"Host(`$tenant`)\""),
            "$state — control: the app routers are rendered:\n$file")
        assertEquals(emptyList<String>(), BLOBS_ROUTER.findAll(file).map { it.groupValues[1] }.toList(), "$state — no blobs router:\n$file")
        assertFalse(file.contains("PathPrefix("), "$state — no router claims a path:\n$file")
        assertFalse(file.contains("veyq-blobs"), "$state — neither the blobs service nor the inert middleware:\n$file")
    }

    private fun assertRoutesOnly(bucket: String, tenant: String) {
        val file = Files.readString(Path.of(CONFIG_PATH))
        val blobs = BLOBS_ROUTER.findAll(file).associate { it.groupValues[1] to it.groupValues[2] }
        // Control: both kinds of blobs router are present — the bootstrap domain's, rendered from configuration,
        // and a projected tenant's. Without it, "every blobs router carries the prefix" holds of an empty set.
        val tenantRouter = "veyq-tenant-${tenant.replace('.', '-')}-blobs"
        assertTrue(blobs.keys.containsAll(listOf("veyq-blobs", tenantRouter)), "the bootstrap and the tenant blobs router:\n$file")
        blobs.forEach { (name, rule) ->
            val domain = if (name == "veyq-blobs") BOOTSTRAP_DOMAIN else HOST.find(rule)!!.groupValues[1]
            assertEquals("Host(`$domain`) && PathPrefix(`/$bucket/`)", rule, "$name routes the bundled store's bucket path")
        }
        assertEquals(listOf("/$bucket/"), PATH_PREFIX.findAll(file).map { it.groupValues[1] }.distinct().toList(),
            "no router anywhere in the file claims any other path:\n$file")
        assertTrue(file.contains("\n    veyq-blobs-inert:\n"), "…and the inert middleware its routers name is defined:\n$file")
    }

    companion object {
        /** Its own file, so this profile's boot-time regenerate never races the other projection tests' reads. */
        const val CONFIG_PATH = "build/test-tenant-ingress-bucket/tenants.yml"
        const val BOOTSTRAP_DOMAIN = "bucket-bootstrap.example.com"
        /** Not the default, and valid under S3's naming rules — a name a restore onto another store might carry. */
        const val BUCKET = "restored-media"
        val BLOBS_ROUTER = Regex("(?m)^    ([a-z0-9-]+-blobs):\\n      rule: \"([^\"]+)\"")
        val HOST = Regex("Host\\(`([^`]+)`\\)")
        val PATH_PREFIX = Regex("PathPrefix\\(`([^`]*)`\\)")
    }
}
